# FEATURE 5: Interactive AI Chatbot
# ================================================================== #
def feature_chat(client: genai.Client, stream: bool = False) -> None:
    print("\n" + "=" * 60)
    print("  💬  AI WORKPLACE CHATBOT")
    print(f"  Model: {MODEL_ID}  |  Streaming: {stream}")
    print("  Type 'exit' or 'quit' to stop.")
    print("=" * 60 + "\n")

    history: list[types.Content] = []

    while True:
        try:
            user_input = input("You: ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\nGoodbye!")
            break

        if not user_input:
            continue
        if user_input.lower() in {"exit", "quit"}:
            print("Goodbye!")
            break

        history.append(
            types.Content(role="user", parts=[types.Part.from_text(text=user_input)])
        )

        try:
            if stream:
                print("Assistant: ", end="", flush=True)
                stream_resp = client.models.generate_content_stream(
                    model=MODEL_ID,
                    contents=history,
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM_INSTRUCTION,
                        temperature=TEMPERATURE,
                        max_output_tokens=MAX_OUTPUT_TOKENS,
                    ),
                )
                full = ""
                for chunk in stream_resp:
                    if chunk.text:
                        print(chunk.text, end="", flush=True)
                        full += chunk.text
                print()
                history.append(
                    types.Content(role="model", parts=[types.Part.from_text(text=full)])
                )
            else:
                resp = client.models.generate_content(
                    model=MODEL_ID,
                    contents=history,
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM_INSTRUCTION,
                        temperature=TEMPERATURE,
                        max_output_tokens=MAX_OUTPUT_TOKENS,
                    ),
                )
                print(f"Assistant: {resp.text}\n")
                history.append(
                    types.Content(role="model", parts=[types.Part.from_text(text=resp.text)])
                )
        except Exception as e:
            print(f"\n[ERROR] {e}\n", file=sys.stderr)

    print(DISCLAIMER)


