# ================================================================== #
# RESPONSIBLE AI
# ================================================================== #
SENSITIVE_PATTERNS = [
    (r"\b\d{3}-\d{2}-\d{4}\b", "US Social Security Number"),
    (r"\b\d{16}\b", "Credit card number"),
    (r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b", "Email address"),
    (r"\b(?:\+27|0)\d{9}\b", "South African phone number"),
    (r"\b\d{13}\b", "South African ID number"),
    (r"password\s*[:=]\s*\S+", "Password"),
    (r"api[_-]?key\s*[:=]\s*\S+", "API key"),
]

HALLUCINATION_MARKERS = [
    r"\[\d+\]",
    r"according to a study",
    r"research shows that",
    r"statistics indicate",
    r"a recent report",
]

logging.basicConfig(
    filename="ai_assistant_audit.log",
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(message)s",
)


def detect_sensitive(text: str) -> list[str]:
    return [label for pattern, label in SENSITIVE_PATTERNS if re.search(pattern, text)]


def validate_input(text: str, feature: str = "general") -> tuple[bool, str]:
    if not text or not text.strip():
        return False, "Input is empty."
    s = text.strip()
    if len(s) < MIN_INPUT_CHARS:
        return False, f"Input too short ({len(s)} chars). Minimum {MIN_INPUT_CHARS}."
    if len(s) > MAX_INPUT_CHARS:
        return False, f"Input too long ({len(s):,} chars). Max {MAX_INPUT_CHARS:,}."

    found = detect_sensitive(s)
    if found:
        msg = "⚠️  Sensitive data detected:\n" + "\n".join(f"   • {x}" for x in found)
        msg += "\n\nRemove before continuing. Do not share confidential data with the AI."
        return False, msg
    return True, s


def flag_hallucinations(text: str) -> list[str]:
    return [
        f"Phrase '{m}' may indicate an unverified claim. Verify independently."
        for m in HALLUCINATION_MARKERS
        if re.search(m, text, re.IGNORECASE)
    ]


def log_audit(feature: str, length: int, success: bool, note: str = "") -> None:
    entry = f"feature={feature} | input_chars={length} | success={success}"
    if note:
        entry += f" | note={note[:80]}"
    logging.info(entry) if success else logging.warning(entry)


# ================================================================== #
# GEMINI CLIENT
# ================================================================== #
def get_client() -> genai.Client:
    api_key = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
    if not api_key:
        print(
            "\n[ERROR] No API key found.\n"
            "Set GEMINI_API_KEY in .env or environment.\n"
            "Get a key: https://aistudio.google.com/apikey\n",
            file=sys.stderr,
        )
        sys.exit(1)
    return genai.Client(api_key=api_key)


def ask(client: genai.Client, prompt: str, temperature: float = TEMPERATURE) -> str:
    resp = client.models.generate_content(
        model=MODEL_ID,
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_INSTRUCTION,
            temperature=temperature,
            max_output_tokens=MAX_OUTPUT_TOKENS,
        ),
    )
    return resp.text


def print_result(text: str) -> None:
    print("\n" + "─" * 60)
    print(text)
    print("─" * 60)
    print(DISCLAIMER)
    warnings = flag_hallucinations(text)
    if warnings:
        print("\n⚠️  VERIFICATION SUGGESTIONS:")
        for w in warnings:
            print(f"   • {w}")


def read_multiline(instruction: str) -> str:
    print(instruction)
    print("Type 'END' on a new line when finished.\n")
    lines = []
    while True:
        try:
            line = input()
        except EOFError:
            break
        if line.strip().upper() == "END":
            break
        lines.append(line)
    return "\n".join(lines).strip()


# ================================================================== #
# FEATURE 1: Smart Email Generator
# ================================================================== #
def feature_email(client: genai.Client) -> None:
    print("\n" + "=" * 60)
    print("  📧  SMART EMAIL GENERATOR")
    print("=" * 60)

    sender = input("Your name: ").strip() or "Sender"
    recipient = input("Recipient name: ").strip() or "Recipient"
    subject = input("Subject / purpose: ").strip()
    key_points = input("Key points (comma-separated): ").strip()
    audience = input("Audience (client / manager / team): ").strip() or "colleague"
    tone = input("Tone (formal / informal / persuasive): ").strip() or "formal"
    length = input("Length (short / medium / detailed): ").strip() or "medium"

    if not subject or not key_points:
        print("❌ Subject and key points are required.")
        return

    prompt = EMAIL_PROMPT.format(
        sender=sender, recipient=recipient, subject=subject,
        key_points=key_points, audience=audience, tone=tone, length=length,
    )

    valid, result = validate_input(prompt, "email")
    if not valid:
        print(f"\n❌ {result}")
        log_audit("email", len(prompt), False, result)
        return

    print("\n⏳ Generating email...")
    try:
        output = ask(client, prompt)
        print_result(output)
        log_audit("email", len(prompt), True)
    except Exception as e:
        print(f"[ERROR] {e}", file=sys.stderr)
        log_audit("email", len(prompt), False, str(e))


