def main() -> None:
    parser = argparse.ArgumentParser(
        description="AI Productivity Assistant — Gemini 3.5 Flash",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  python app.py                  # interactive menu\n"
            "  python app.py email            # Smart Email Generator\n"
            "  python app.py notes            # Meeting Notes Summarizer\n"
            "  python app.py plan             # AI Task Planner\n"
            "  python app.py research         # AI Research Assistant\n"
            "  python app.py chat             # Chatbot\n"
            "  python app.py chat --stream    # Chatbot with streaming\n"
        ),
    )
    parser.add_argument(
        "command", nargs="?",
        choices=["email", "notes", "plan", "research", "chat"],
        help="Feature to run directly",
    )
    parser.add_argument(
        "--stream", action="store_true",
        help="Stream chatbot responses token-by-token",
    )
    args = parser.parse_args()

    client = get_client()

    if args.command == "email":
        feature_email(client)
    elif args.command == "notes":
        feature_notes(client)
    elif args.command == "plan":
        feature_plan(client)
    elif args.command == "research":
        feature_research(client)
    elif args.command == "chat":
        feature_chat(client, stream=args.stream)
    else:
        menu(client)


if __name__ == "__main__":
    main()
